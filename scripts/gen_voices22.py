def ffprobe_dur(path):
    r = subprocess.run(['ffprobe', '-v', 'quiet', '-show_entries', 'format=duration',
                        '-of', 'csv=p=0', path], capture_output=True, text=True, timeout=20)
    return round(float(r.stdout.strip()), 2)

async def gen_one(key, who, text, sem):
    voice, rate, pitch, af = PROFILE[who]
    raw = f'{OUT_DIR}/{key}_raw.mp3'
    fin = f'{OUT_DIR}/{key}.mp3'
    async with sem:
        for attempt in range(4):
            try:
                tts = edge_tts.Communicate(text, voice, rate=rate, pitch=pitch)
                await tts.save(raw)
                if os.path.getsize(raw) > 2000:
                    break
            except Exception as e:
                if attempt == 3:
                    print(f'  !! FAIL {key}: {e}', flush=True)
                    return None
                await asyncio.sleep(2.5)
    try:
        subprocess.run(['ffmpeg', '-y', '-v', 'quiet', '-i', raw,
                        '-af', af, '-ar', '24000', '-ac', '1', '-b:a', '32k', fin],
                       check=True, timeout=40)
    except Exception as e:
        print(f'  !! ffmpeg FAIL {key}: {e}', flush=True)
        return None
    os.remove(raw)
    return fin

async def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    sem = asyncio.Semaphore(5)
    print(f'generating {len(LINES)} clips...', flush=True)
    tasks = {k: asyncio.create_task(gen_one(k, w, t, sem)) for k, w, t in LINES}
    ok, fail = 0, []
    entries = []
    for key, who, text in LINES:
        p = await tasks[key]
        if not p:
            fail.append(key); continue
        d = ffprobe_dur(p)
        b = open(p, 'rb').read()
        b64 = base64.b64encode(b).decode()
        entries.append((key, d, b64))
        ok += 1
        if ok % 20 == 0:
            print(f'  ... {ok}/{len(LINES)}', flush=True)
    print(f'OK={ok} FAIL={len(fail)} {fail}', flush=True)
    if fail:
        sys.exit(1)
    total = sum(len(e[2]) for e in entries)
    with open(DATA_JS, 'w', encoding='utf-8') as f:
        f.write('/* ==================================================================\n')
        f.write('   سه طبقه تا مرگ — نسخه‌ی ۲۲٫۰ — داده‌ی صداهای گفتار (تولید خودکار)\n')
        f.write(f'   {len(entries)} کلیپ MP3 با edge-tts + پس‌پردازش ffmpeg — پایه ۶۴\n')
        f.write('   شخصیت‌ها (۷ صدای متمایز):\n')
        f.write('     n راوی (بم/سینمایی) / a ارشان (جوان/پرانرژی) / p سهند (آرام/مسئول) /\n')
        f.write('     m دکتر مریم (زن/دقیق) / r بی‌سیم (افکت رادیویی) /\n')
        f.write('     b نگهبان (هیولا) / d دستفروش (حیله‌گر)\n')
        f.write('   ================================================================== */\n')
        f.write('const VOICES22 = {\n')
        for key, d, b64 in entries:
            f.write(f'{key}:{{d:{d},a:"data:audio/mpeg;base64,{b64}"}},\n')
        f.write('};\n')
    print(f'written {DATA_JS}: {total//1024}KB base64, {len(entries)} clips', flush=True)
    # خلاصه‌ی مدت‌ها برای دیباگ
    with open(f'{OUT_DIR}/_durations.json', 'w') as f:
        json.dump({k: d for k, d, _ in entries}, f)

if __name__ == '__main__':
    asyncio.run(main())
