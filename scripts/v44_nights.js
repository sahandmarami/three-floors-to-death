/* ---------------- ۱) رجیستری مرکزی دیالوگ ----------------
   هر خط: id → { ch, n, who, v (کلید صوتی یا null), text, purpose, emo, once } */
const DLG_REG = {};
function D44(id, ch, n, who, v, text, purpose, emo, once) {
  DLG_REG[id] = { id, ch, n, who, v: v || null, text, purpose: purpose || '', emo: emo || 'normal', once: once !== false };
}
/* ساخت آرایهٔ خطوط از شناسه‌ها — اجرا شده‌ها ثبت می‌شوند */
function R44(ids) {
  const out = [];
  for (const id of ids) {
    const L = DLG_REG[id];
    if (!L) { console.warn('[DLG_REG] missing', id); continue; }
    out.push({ id, who: L.who, v: L.v, text: L.text });
    if (L.once) DEC44.played[id] = true;
  }
  return out;
}
/* شرط‌گذار: فقط اگر شرط برقرار بود خط‌ها را برگردان */
function R44if(cond, ids) { return cond ? R44(ids) : []; }

/* ---------------- ۲) وضعیت تصمیم‌ها ---------------- */
