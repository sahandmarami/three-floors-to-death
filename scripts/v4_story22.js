/* گفتگوی پس از موج (پنل روز) — ۱.۲ ثانیه بعد از طلوع */
let _storyDayTimer = null;
function storyAfterWave() {
  try {
    const w = state.wave;
    const dl = STORY22.afterWave[w];
    if (!dl || !dl.length) return;
    if (_storyDayTimer) clearTimeout(_storyDayTimer);
    _storyDayTimer = setTimeout(() => {
      _storyDayTimer = null;
      try {
        if (state.mode !== 'day' || DLG.active) return;
        DLG.start(dl, null);
      } catch (e) {}
    }, 1200);
  } catch (e) {}
}

/* گفتگوی پیش از موج پایانی فصل (وقتی «شب شود» آخرین موج فصل را آغاز می‌کند) */
function storyPreNight() {
  try {
    const next = state.wave + 1;
    const dl = STORY22.preFinalWave[next];
    if (!dl || !dl.length) return false;
    DLG.start(dl, null);
    return true;
  } catch (e) { return false; }
}

/* گفتگوی پایان فصل: بعد از پایانِ آن، انتقال فصل شروع می‌شود */
let _storyChEndGuard = 0;
function storyChapterEnd(ch, done) {
  try {
    const dl = STORY22.chEnd[ch];
    const msg = STORY22.chEndMsg[ch];
    if (msg) setAnnounce('📜 ' + msg, 'آماده‌ی حرکت شو...', 5);
    if (!dl || !dl.length) { if (done) done(); return; }
    const now = performance.now();
    if (now - _storyChEndGuard < 500) return;      // ضد دوبار فراخوانی
    _storyChEndGuard = now;
    state.chapterEnding = true;                    /* حلقه‌ی بازی موجِ تمام‌شده را دوباره کامل نکند */
    let fired = false;
    const fin = () => {
      state.chapterEnding = false;
      if (!fired) { fired = true; if (done) done(); }
    };
    DLG.start(dl, fin);
    setTimeout(fin, 42000);                        // مهلت ایمنی
  } catch (e) { if (done) done(); }
}

/* گفتگوی شروع فصل (کارت فصل) */
function storyChapterStart(ch) {
  try {
    const dl = STORY22.chStart[ch];
    if (!dl || !dl.length) return;
    setTimeout(() => { try { if (!DLG.active) DLG.start(dl, null); } catch (e) {} }, 1500);
  } catch (e) {}
}
